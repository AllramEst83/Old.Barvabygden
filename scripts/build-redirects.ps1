<#
.SYNOPSIS
    Generates the 301 redirect block in .htaccess from scripts/path-manifest.csv.

.DESCRIPTION
    One "Redirect 301" line per moved page (.htm/.html) and per moved PDF, written between the
    marker comments in .htaccess (appended when the markers are missing). Media files get no
    redirects. A file whose new home is not deployed (attic/, migration-sources/) redirects to "/".
    Fragments, tooling, docs and junk are skipped. Output is sorted and deterministic.

    A second block, between "# BEGIN image redirects" and "# END image redirects", holds 301s for
    images whose URL changed (rename, merge, format change), generated from scripts/image-manifest.csv.
    Quarantined images (moved to attic/) get none. A redirect source that is still a live file, or a
    prefix of one, is an error (Apache's Redirect matches by prefix).

.PARAMETER WhatIf
    Print the block instead of writing .htaccess.

.EXAMPLE
    ./scripts/build-redirects.ps1
#>
param([switch]$WhatIf)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$htaccess = Join-Path $root '.htaccess'
$begin = '# BEGIN redirects (generated by scripts/build-redirects.ps1 - do not edit by hand)'
$end = '# END redirects'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Esc-Url([string]$path) { ($path.Split('/') | ForEach-Object { [System.Uri]::EscapeDataString($_) }) -join '/' }
function Quote([string]$s) { '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

$rows = Import-Csv (Join-Path $PSScriptRoot 'path-manifest.csv') -Encoding UTF8 |
    Where-Object { $_.class -notin 'fragment', 'tooling', 'docs', 'junk' -and $_.old_path -match '\.(html?|pdf)$' }

$lines = New-Object System.Collections.Generic.List[string]
foreach ($r in ($rows | Sort-Object { $_.old_path.ToLowerInvariant() }, { $_.old_path })) {
    $target = if ($r.new_path -match '^(attic|migration-sources)/') { '/' } else { '/' + (Esc-Url $r.new_path) }
    $lines.Add("Redirect 301 $(Quote ('/' + $r.old_path)) $(Quote $target)")
}
$block = @($begin) + $lines + @($end)

# ---- Image redirects (image-manifest.csv): old URL -> final URL, skipping quarantine and unchanged rows ----
$imgBegin = '# BEGIN image redirects (generated by scripts/build-redirects.ps1 - do not edit by hand)'
$imgEnd = '# END image redirects'
$imgRows = @(Import-Csv (Join-Path $PSScriptRoot 'image-manifest.csv') -Encoding UTF8 |
        Where-Object { $_.action -in 'rename', 'convert', 'merge' -and $_.old_path -cne $_.new_path })
$live = @(git -c core.quotepath=off ls-files | Where-Object { $_ -match '^(assets/images|barva-bladet)/' })
$liveSet = New-Object System.Collections.Generic.HashSet[string]([StringComparer]::Ordinal)
foreach ($l in $live) { [void]$liveSet.Add($l) }
$problems = New-Object System.Collections.Generic.List[string]
$imgLines = New-Object System.Collections.Generic.List[string]
foreach ($r in ($imgRows | Sort-Object { $_.old_path.ToLowerInvariant() }, { $_.old_path })) {
    if (-not $liveSet.Contains($r.new_path)) { $problems.Add("target is not a tracked file: $($r.new_path)"); continue }
    foreach ($l in $live) { if ($l.StartsWith($r.old_path, [StringComparison]::Ordinal)) { $problems.Add("redirect source $($r.old_path) is a live file or a prefix of $l") ; break } }
    $imgLines.Add("Redirect 301 $(Quote ('/' + $r.old_path)) $(Quote ('/' + (Esc-Url $r.new_path)))")
}
if ($problems.Count) { $problems | ForEach-Object { Write-Error $_ -ErrorAction Continue }; exit 1 }
$imgBlock = @($imgBegin) + $imgLines + @($imgEnd)

if ($WhatIf) { $block; $imgBlock; Write-Host "$($lines.Count) page/PDF redirects, $($imgLines.Count) image redirects" -ForegroundColor Green; exit 0 }

$text = [System.IO.File]::ReadAllText($htaccess, $utf8)
$nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
$new = ($block -join $nl)
$pattern = '(?s)' + [regex]::Escape($begin) + '.*?' + [regex]::Escape($end)
if ($text -match $pattern) { $text = [regex]::Replace($text, $pattern, { param($m) $new }) }
else { $text = $text.TrimEnd() + $nl + $nl + $new + $nl }

$newImg = ($imgBlock -join $nl)
$imgPattern = '(?s)' + [regex]::Escape($imgBegin) + '.*?' + [regex]::Escape($imgEnd)
if ($text -match $imgPattern) { $text = [regex]::Replace($text, $imgPattern, { param($m) $newImg }) }
else {
    # first run: place the image block right after the page block
    $text = $text.Replace($end, $end + $nl + $newImg)
}
[System.IO.File]::WriteAllText($htaccess, $text, $utf8)
Write-Host "Wrote $($lines.Count) page/PDF redirects and $($imgLines.Count) image redirects to .htaccess" -ForegroundColor Green
