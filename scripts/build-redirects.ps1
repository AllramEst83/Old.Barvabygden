<#
.SYNOPSIS
    Generates the 301 redirect block in .htaccess from scripts/path-manifest.csv.

.DESCRIPTION
    One "Redirect 301" line per moved page (.htm/.html) and per moved PDF, written between the
    marker comments in .htaccess (appended when the markers are missing). Media files get no
    redirects. A file whose new home is not deployed (attic/, migration-sources/) redirects to "/".
    Fragments, tooling, docs and junk are skipped. Output is sorted and deterministic.

.PARAMETER WhatIf
    Print the block instead of writing .htaccess.

.EXAMPLE
    ./scripts/build-redirects.ps1
#>
param([switch]$WhatIf)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$htaccess = Join-Path $root '.htaccess'
$begin = '# BEGIN redirects (generated by scripts/build-redirects.ps1 - do not edit by hand)'
$end = '# END redirects'
$utf8 = New-Object System.Text.UTF8Encoding($false)

function Esc-Url([string]$path) { ($path.Split('/') | ForEach-Object { [System.Uri]::EscapeDataString($_) }) -join '/' }
function Quote([string]$s) { '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

$rows = Import-Csv (Join-Path $PSScriptRoot 'path-manifest.csv') -Encoding UTF8 |
    Where-Object { $_.class -notin 'fragment', 'tooling', 'docs', 'junk' -and $_.old_path -match '\.(html?|pdf)$' }

$lines = New-Object System.Collections.Generic.List[string]
foreach ($r in ($rows | Sort-Object { $_.old_path.ToLowerInvariant() }, { $_.old_path })) {
    $target = if ($r.new_path -match '^(attic|migration-sources)/') { '/' } else { '/' + (Esc-Url $r.new_path) }
    $lines.Add("Redirect 301 $(Quote ('/' + $r.old_path)) $(Quote $target)")
}
$block = @($begin) + $lines + @($end)

if ($WhatIf) { $block; Write-Host "$($lines.Count) redirects" -ForegroundColor Green; exit 0 }

$text = [System.IO.File]::ReadAllText($htaccess, $utf8)
$nl = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
$new = ($block -join $nl)
$pattern = '(?s)' + [regex]::Escape($begin) + '.*?' + [regex]::Escape($end)
if ($text -match $pattern) { $text = [regex]::Replace($text, $pattern, { param($m) $new }) }
else { $text = $text.TrimEnd() + $nl + $nl + $new + $nl }
[System.IO.File]::WriteAllText($htaccess, $text, $utf8)
Write-Host "Wrote $($lines.Count) redirects to .htaccess" -ForegroundColor Green
